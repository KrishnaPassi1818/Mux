/// Request ID carried from the gateway or generated by the router.
#[derive(Clone, Copy)]
pub struct RequestId(pub Uuid);

/// Propagate one UUID through every handler, event and response header.
pub async fn request_id_middleware(mut request: Request, next: Next) -> Response {
    let request_id = request
        .headers()
        .get("x-request-id")
        .and_then(|value| value.to_str().ok())
        .and_then(|value| Uuid::parse_str(value).ok())
        .unwrap_or_else(Uuid::new_v4);
    request.extensions_mut().insert(RequestId(request_id));
    let span = tracing::info_span!("router_request", request_id = %request_id);
    let mut response = next.run(request).instrument(span).await;
    if let Ok(value) = HeaderValue::from_str(&request_id.to_string()) {
        response
            .headers_mut()
            .insert(HeaderName::from_static("x-request-id"), value);
    }
    response
}

/// Lightweight liveness/dependency status.
pub async fn health(State(state): State<Arc<AppState>>) -> Response {
    let (ollama, redis) = tokio::join!(state.backend.tags(), state.cache.healthy());
    let ollama_ok = ollama.is_ok();
    let redis_ok = redis;
    let status = if ollama_ok && redis_ok {
        "healthy"
    } else {
        "degraded"
    };
    let services = BTreeMap::from([
        (
            "router",
            ServiceHealth {
                status: "healthy",
                detail: None,
            },
        ),
        (
            "ollama",
            ServiceHealth {
                status: if ollama_ok { "healthy" } else { "unavailable" },
                detail: if ollama_ok {
                    None
                } else {
                    Some("Ollama API is unreachable".to_owned())
                },
            },
        ),
        (
            "redis",
            ServiceHealth {
                status: if redis_ok { "healthy" } else { "degraded" },
                detail: if redis_ok {
                    None
                } else {
                    Some("Cache is bypassed; inference remains available".to_owned())
                },
            },
        ),
    ]);
    Json(HealthResponse { status, services }).into_response()
}

#[derive(Serialize)]
struct HealthResponse<'a> {
    status: &'a str,
    services: BTreeMap<&'a str, ServiceHealth<'a>>,
}
#[derive(Serialize)]
struct ServiceHealth<'a> {
    status: &'a str,
    #[serde(skip_serializing_if = "Option::is_none")]
    detail: Option<String>,
}

/// Configured model registry decorated with the latest Ollama state.
pub async fn models(State(state): State<Arc<AppState>>) -> Response {
    let (tags, loaded) = tokio::join!(state.backend.tags(), state.backend.loaded_models());
    let tags = tags.ok();
    let loaded = loaded.unwrap_or_default();
    if let Some(first) = loaded.first() {
        state.set_loaded_model(&first.name);
    }
    let loaded_by_name = loaded
        .iter()
        .map(|model| (model.name.as_str(), model.size_vram))
        .collect::<BTreeMap<_, _>>();
    let items = state
        .config
        .models
        .iter()
        .filter_map(|model| {
            let tier = crate::models::Tier::parse(&model.tier)?;
            let size_vram = loaded_by_name.get(model.name.as_str()).copied();
            Some(ModelInfo {
                name: model.name.clone(),
                tier,
                available: tags
                    .as_ref()
                    .is_some_and(|names| names.contains(&model.name)),
                loaded: size_vram.is_some(),
                max_concurrency: model.max_concurrency,
                timeout_ms: model.timeout_ms,
                size_bytes: model.size_bytes,
                size_vram_bytes: size_vram,
            })
        })
        .collect();
    Json(ModelsResponse { models: items }).into_response()
}

/// Return rolling-window stats for the live dashboard.
pub async fn stats(State(state): State<Arc<AppState>>) -> Json<StatsResponse> {
    Json(state.stats().await)
}

/// Flush only the router response-cache namespace.
pub async fn flush_cache(
    State(state): State<Arc<AppState>>,
    Extension(request_id): Extension<RequestId>,
) -> Response {
    match state.cache.flush().await {
        Ok(removed) => Json(serde_json::json!({"ok": true, "removed": removed})).into_response(),
        Err(error) => {
            state.metrics.cache_errors.inc();
            tracing::warn!(request_id = %request_id.0, %error, "cache flush failed");
            error_response(AppError::UpstreamUnavailable, request_id.0)
        }
    }
}

/// Return metrics in Prometheus text exposition format.
pub async fn metrics(State(state): State<Arc<AppState>>) -> Response {
    match state.metrics.encode() {
        Ok(body) => (
            [(
                axum::http::header::CONTENT_TYPE,
                "text/plain; version=0.0.4; charset=utf-8",
            )],
            body,
        )
            .into_response(),
        Err(error) => (StatusCode::INTERNAL_SERVER_ERROR, error.to_string()).into_response(),
    }
}

/// Dry-run classification and policy selection without an inference call.
pub async fn preview(
    State(state): State<Arc<AppState>>,
    Extension(request_id): Extension<RequestId>,
    body: Result<Json<PreviewRequest>, JsonRejection>,
) -> Response {
    let request = match body {
        Ok(Json(request)) => request,
        Err(rejection) => {
            return error_response(
                AppError::InvalidRequest(rejection.body_text()),
                request_id.0,
            )
        }
    };
    if let Err(error) = validate_messages(&request.messages) {
        return error_response(error, request_id.0);
    }
    let chat = ChatRequest {
        messages: request.messages,
        mode: request.mode,
        model: request.model,
        options: ChatOptions::default(),
        use_cache: false,
        request_id: Some(request_id.0),
    };
    let classification = state.classifier.classify(&chat);
    let decision = policy::PolicyEngine::new(&state.config, &state.queue).select(
        &chat,
        &classification,
        state.loaded_model().as_deref(),
    );
    match decision {
        Ok(value) => Json(value).into_response(),
        Err(error) => error_response(error, request_id.0),
    }
}

fn validate_messages(messages: &[crate::models::Message]) -> Result<(), AppError> {
    if messages.is_empty() || messages.len() > 50 {
        return Err(AppError::InvalidRequest(
            "messages must contain between 1 and 50 items.".to_owned(),
        ));
    }
    if messages
        .iter()
        .map(|message| message.content.len())
        .sum::<usize>()
        > 32_768
    {
        return Err(AppError::InvalidRequest(
            "Combined message content must not exceed 32 KB.".to_owned(),
        ));
    }
    if !messages
        .iter()
        .any(|message| matches!(message.role, crate::models::Role::User))
    {
        return Err(AppError::InvalidRequest(
            "At least one user message is required.".to_owned(),
        ));
    }
    Ok(())
}

/// Export validation to the streaming endpoint.
pub(crate) fn validate_chat_request(request: &ChatRequest) -> Result<(), AppError> {
    validate_messages(&request.messages)?;
    if request.mode == Mode::Force && request.model.is_none() {
        return Err(AppError::InvalidRequest(
            "model is required when mode is force.".to_owned(),
        ));
    }
    if !(0.0..=2.0).contains(&request.options.temperature) {
        return Err(AppError::InvalidRequest(
            "temperature must be between 0 and 2.".to_owned(),
        ));
    }
    if !(0.0..=1.0).contains(&request.options.top_p) || request.options.top_p == 0.0 {
        return Err(AppError::InvalidRequest(
            "top_p must be greater than 0 and at most 1.".to_owned(),
        ));
    }
    if !(256..=32_768).contains(&request.options.num_ctx) {
        return Err(AppError::InvalidRequest(
            "num_ctx must be between 256 and 32768.".to_owned(),
        ));
    }
    if request
        .options
        .num_predict
        .is_some_and(|value| value == 0 || value > 8192)
    {
        return Err(AppError::InvalidRequest(
            "num_predict must be between 1 and 8192.".to_owned(),
        ));
    }
    Ok(())
}

/// Convert Axum's JSON extractor rejection to the shared API error shape.
pub(crate) fn json_error(rejection: JsonRejection, request_id: Uuid) -> Response {
    error_response(AppError::InvalidRequest(rejection.body_text()), request_id)
}

